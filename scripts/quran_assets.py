AUDIO_KBPS = 64
PACK_NAME = re.compile(r'[a-z][a-z0-9_]*')
PAGES_PACK = 'quran_pages'
ARCHIVE_PREFIX = 'v1/packs/'
DOWNLOAD_TRIES = 5
# Where each reciter's recordings were originally published, for provenance and fetch-origin.
