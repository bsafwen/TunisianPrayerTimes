#!/usr/bin/env python3
"""
Truncated VSOP87D Earth series for the shared prayer engine's VSOP87 sun (E14, plan 6.2).

Reads the full series (VSOP87D.ear, Bretagnon & Francou 1988, from IMCCE), keeps every term whose
amplitude A is at least 1e-8 (621 of the 2,425 terms) and writes:

  vsop87d_earth_terms.tsv   the kept terms, read by prayer_engine_reference.py
  .../engine/Vsop87Terms.kt the same terms as Kotlin arrays for the shared module

Over 2020-2100 the kept terms stay within 0.038" of the full series in longitude and 0.024" in
latitude (about 0.003 s of time), measured with --check.

Usage:
  python scripts/prayer_formula/vsop87_terms.py path/to/VSOP87D.ear
  python scripts/prayer_formula/vsop87_terms.py path/to/VSOP87D.ear --check
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TSV_PATH = Path(__file__).resolve().parent / "vsop87d_earth_terms.tsv"
KOTLIN_PATH = ROOT / "multiplatform/shared/src/commonMain/kotlin/com/tunisianprayertimes/engine/Vsop87Terms.kt"
MIN_AMPLITUDE = 1e-8
VARIABLES = {1: "L", 2: "B", 3: "R"}


def load(path: Path) -> dict[int, dict[int, list[tuple[str, str, str]]]]:
    """Terms as (A, B, C) strings, kept verbatim, by variable (1 L, 2 B, 3 R) and power of tau."""
    series: dict[int, dict[int, list[tuple[str, str, str]]]] = {1: {}, 2: {}, 3: {}}
    current: list[tuple[str, str, str]] | None = None
    for line in path.read_text(encoding="ascii").splitlines():
        if "VARIABLE" in line:
            variable = int(line.split("VARIABLE")[1].split()[0])
            power = int(line.split("*T**")[1].split()[0])
            current = series[variable].setdefault(power, [])
            continue
        if not line.strip():
            continue
        cells = line.split()
        assert current is not None
        current.append((cells[-3], cells[-2], cells[-1]))
    return series


def truncate(series, amplitude=MIN_AMPLITUDE):
    return {v: {p: [t for t in terms if float(t[0]) >= amplitude] for p, terms in powers.items()}
            for v, powers in series.items()}


def value(series, variable: int, tau: float) -> float:
    total = 0.0
    for power, terms in series[variable].items():
        s = 0.0
        for a, b, c in terms:
            s += float(a) * math.cos(float(b) + float(c) * tau)
        total += s * tau ** power
    return total


def write_tsv(kept) -> None:
    lines = [
        "# Truncated VSOP87D Earth series (Bretagnon & Francou 1988, IMCCE): terms with A >= 1e-8.",
        "# variable (L, B, R: radians, radians, AU)\tpower of tau\tA\tB\tC; the series is",
        "# sum over powers k of tau^k * sum A*cos(B + C*tau), tau in Julian millennia of TT from J2000.0.",
        "# Generated by vsop87_terms.py; do not edit.",
    ]
    for variable, powers in kept.items():
        for power, terms in sorted(powers.items()):
            for a, b, c in terms:
                lines.append(f"{VARIABLES[variable]}\t{power}\t{a}\t{b}\t{c}")
    TSV_PATH.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


def write_kotlin(kept) -> None:
    out = [
        "package com.tunisianprayertimes.engine",
        "",
        "// Generated by scripts/prayer_formula/vsop87_terms.py from VSOP87D.ear; do not edit.",
        "",
        "/**",
        " * The VSOP87D Earth series (Bretagnon & Francou 1988, IMCCE) truncated to the terms with an",
        " * amplitude of at least 1e-8: within 0.038\" of the full series over 2020-2100. Each array holds",
        " * one power of tau as (A, B, C) triples, the term being A cos(B + C tau).",
        " */",
        "internal object Vsop87Terms {",
    ]
    for variable, powers in kept.items():
        name = VARIABLES[variable]
        out.append(f"    val {name}: List<DoubleArray> by lazy {{ listOf({', '.join(f'{name}{p}' for p in sorted(powers))}) }}")
    out.append("")
    for variable, powers in kept.items():
        name = VARIABLES[variable]
        for power, terms in sorted(powers.items()):
            out.append(f"    private val {name}{power} get() = doubleArrayOf(")
            for a, b, c in terms:
                out.append(f"        {a}, {b}, {c},")
            out.append("    )")
            out.append("")
    out[-1] = "}"
    KOTLIN_PATH.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_PATH.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


def check(full, kept) -> None:
    asec = math.pi / 180 / 3600
    taus = [((2458850.5 + d) - 2451545.0) / 365250.0 for d in range(0, 29586, 11)]  # 2020-01-01 .. 2100-12-31
    worst = {1: 0.0, 2: 0.0, 3: 0.0}
    for tau in taus:
        for variable in worst:
            worst[variable] = max(worst[variable], abs(value(kept, variable, tau) - value(full, variable, tau)))
    print(f"{sum(len(t) for p in kept.values() for t in p.values())} terms kept; over 2020-2100 "
          f"max |dL| {worst[1] / asec:.4f}\", |dB| {worst[2] / asec:.4f}\", |dR| {worst[3]:.2e} AU")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ear", type=Path, help="the full VSOP87D.ear file")
    parser.add_argument("--check", action="store_true", help="measure the truncation error instead of writing")
    args = parser.parse_args()
    full = load(args.ear)
    kept = truncate(full)
    if args.check:
        check(full, kept)
        return 0
    write_tsv(kept)
    write_kotlin(kept)
    print(f"wrote {TSV_PATH.relative_to(ROOT)} and {KOTLIN_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
